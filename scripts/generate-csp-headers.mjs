#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Writes the browser origin's response headers, including the content policy.
 *
 * The origin this protects stores the local app's session token in browser
 * storage next to the account session, so any script injected into that page
 * reads the token and gains file access on every paired machine. The policy is
 * the cheapest high-impact change in the feature (FR-025/SC-008).
 *
 * Hashes for the two inline scripts are computed here rather than written by
 * hand, so editing a block without regenerating its hash fails the build
 * instead of shipping a page that silently refuses to run its own scripts.
 */

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const INDEX = path.join(root, 'apps/web/index.html');
const HEADERS = path.join(root, 'apps/web/public/_headers');

/**
 * Supabase endpoints the page is allowed to talk to.
 *
 * Keep this generated, committed policy independent of the build machine's
 * environment. The exact project URL is already covered by these host
 * wildcards; adding it when VITE_SUPABASE_URL happens to be exported makes the
 * same source tree generate different bytes locally and in CI.
 */
const SUPABASE_ORIGINS = 'https://*.supabase.co wss://*.supabase.co';

/** Every inline `<script>` body in the document, in order. */
function inlineScripts(html) {
  return [...html.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/gu)].map(
    match => match[1]
  );
}

function sha256(source) {
  return `'sha256-${createHash('sha256').update(source, 'utf8').digest('base64')}'`;
}

// Git checks the file out with CRLF on Windows. Hash the canonical document
// bytes so a single source revision produces the same committed policy on
// every runner; Vite emits the normalized text during the production build.
const html = readFileSync(INDEX, 'utf8').replaceAll('\r\n', '\n');
const scriptHashes = inlineScripts(html).map(sha256);
if (scriptHashes.length === 0) {
  process.stderr.write('csp: no inline scripts found; the policy would be wrong.\n');
  process.exit(1);
}

/**
 * The local app, across ports.
 *
 * Production, beta and development bind different ports, and a policy naming
 * one literal port would break the other two. `http://127.0.0.1:*` covers the
 * loopback host without widening to anything reachable from outside the
 * machine.
 */
const LOCAL_APP = 'http://127.0.0.1:* http://localhost:*';

const policy = [
  "default-src 'self'",
  `script-src 'self' ${scriptHashes.join(' ')}`,
  // The stylesheet is a file; inline styles assigned through `element.style`
  // are CSSOM writes and are not covered by this directive.
  "style-src 'self' 'unsafe-inline'",
  `connect-src 'self' ${SUPABASE_ORIGINS} ${LOCAL_APP}`,
  // `data:` for an inline SVG in the stylesheet, `blob:` for a generated
  // download preview, and the avatar host for signed-in users.
  "img-src 'self' data: blob: https://lh3.googleusercontent.com",
  `media-src 'self' blob: ${LOCAL_APP}`,
  `frame-src ${LOCAL_APP}`,
  "frame-ancestors 'none'",
  "base-uri 'none'",
  // Sign-in is a redirect, not a form post. Widen to 'self' if a real form
  // target ever appears.
  "form-action 'none'",
  "object-src 'none'"
].join('; ');

const headers = `# Generated by scripts/generate-csp-headers.mjs — do not edit by hand.
#
# The hashes below cover the inline scripts in apps/web/index.html. Editing one
# without regenerating this file means the browser refuses to run it, so the
# generation is a build step rather than a checklist item.

/*
  Content-Security-Policy: ${policy}
  Strict-Transport-Security: max-age=31536000; includeSubDomains
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: accelerometer=(), autoplay=(), camera=(), display-capture=(), encrypted-media=(), geolocation=(), gyroscope=(), magnetometer=(), microphone=(), midi=(), payment=(), usb=(), xr-spatial-tracking=()
  Cross-Origin-Opener-Policy: same-origin
  X-Frame-Options: DENY

/
  Cache-Control: no-cache, no-store, must-revalidate
  X-Robots-Tag: index, follow

/index.html
  Cache-Control: no-cache, no-store, must-revalidate

/assets/*
  Cache-Control: public, max-age=0, must-revalidate
`;

if (process.argv.includes('--check')) {
  const current = readFileSync(HEADERS, 'utf8');
  if (current.replaceAll('\r\n', '\n') !== headers) {
    process.stderr.write(
      'csp: apps/web/public/_headers is stale. Run `npm run generate:csp` and commit the result.\n'
    );
    process.exit(1);
  }
  process.stdout.write('csp: headers are current.\n');
} else {
  writeFileSync(HEADERS, headers);
  process.stdout.write(`csp: wrote ${scriptHashes.length} script hash(es).\n`);
}
