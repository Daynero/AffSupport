import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  DRIVE_OAUTH_MODES,
  GEO_CODES,
  LANGUAGE_CODES,
  MATERIAL_CATEGORIES,
  MATERIAL_CLASSIFIER_VERSION,
  ROLE_PERMISSIONS,
  TEAM_BASE_ROLES,
  TEAM_CONNECTION_STATES,
  TEAM_CONTRACT_SETTINGS,
  TEAM_ERROR_CODES,
  TEAM_INVITATION_DELIVERY_STATES,
  TEAM_INVITATION_STATES,
  TEAM_MATERIAL_LIFECYCLES,
  TEAM_OPERATION_KINDS,
  TEAM_OPERATION_STATES,
  TEAM_PERMISSION_FLAGS,
  TEAM_ROLES,
  TRANSCRIPT_EXTENSIONS,
  TRANSCRIPT_INGEST_STATES
} from '../packages/shared/dist/types.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const defaultOutput = resolve(root, 'supabase/migrations/20260801090000_team_contract_seed.sql');

function fail(message) {
  process.stderr.write(`${message}\n`);
  process.exit(1);
}

function sqlLiteral(value) {
  return `'${String(value).replaceAll("'", "''")}'`;
}

function jsonLiteral(value) {
  return `${sqlLiteral(JSON.stringify(value))}::jsonb`;
}

function values(rows) {
  return rows.map(row => `  (${row.join(', ')})`).join(',\n');
}

function generatedSql() {
  const settings = {
    ...TEAM_CONTRACT_SETTINGS,
    driveOAuthModes: DRIVE_OAUTH_MODES,
    invitationStates: TEAM_INVITATION_STATES,
    invitationDeliveryStates: TEAM_INVITATION_DELIVERY_STATES,
    connectionStates: TEAM_CONNECTION_STATES,
    operationStates: TEAM_OPERATION_STATES,
    operationKinds: TEAM_OPERATION_KINDS,
    materialCategories: MATERIAL_CATEGORIES,
    materialLifecycles: TEAM_MATERIAL_LIFECYCLES,
    transcriptExtensions: TRANSCRIPT_EXTENSIONS,
    transcriptIngestStates: TRANSCRIPT_INGEST_STATES,
    materialClassifierVersion: MATERIAL_CLASSIFIER_VERSION
  };
  const roleRows = TEAM_ROLES.flatMap(role =>
    TEAM_PERMISSION_FLAGS.map(permission => [
      sqlLiteral(role),
      sqlLiteral(permission),
      ROLE_PERMISSIONS[role][permission] ? 'true' : 'false'
    ])
  );
  const settingRows = Object.entries(settings).map(([key, value]) => [
    sqlLiteral(key.replace(/[A-Z]/g, letter => `_${letter.toLowerCase()}`)),
    jsonLiteral(value)
  ]);

  return `-- GENERATED by scripts/generate-team-contract-sql.mjs. DO NOT EDIT BY HAND.
-- Canonical source: packages/shared/src/team/*.ts

create table public.team_contract_settings (
  key text primary key,
  value jsonb not null
);

create table public.team_roles (
  role text primary key,
  is_base_role boolean not null,
  constraint team_roles_value_check check (role in (${TEAM_ROLES.map(sqlLiteral).join(', ')}))
);

create table public.team_permissions (
  permission text primary key,
  constraint team_permissions_value_check check (
    permission in (${TEAM_PERMISSION_FLAGS.map(sqlLiteral).join(', ')})
  )
);

create table public.role_permissions (
  role text not null references public.team_roles(role) on delete restrict,
  permission text not null references public.team_permissions(permission) on delete restrict,
  allowed boolean not null,
  primary key (role, permission)
);

create table public.team_error_codes (
  code text primary key
);

create table public.geo_options (
  code text primary key,
  constraint geo_options_iso_alpha2 check (code ~ '^[A-Z]{2}$')
);

create table public.language_options (
  code text primary key,
  constraint language_options_bcp47_shape check (
    code ~ '^[a-z]{2,3}(-[A-Za-z0-9]{2,8})*$'
  )
);

insert into public.team_contract_settings (key, value) values
${values(settingRows)};

insert into public.team_roles (role, is_base_role) values
${values(TEAM_ROLES.map(role => [sqlLiteral(role), /** @type {readonly string[]} */ (TEAM_BASE_ROLES).includes(role) ? 'true' : 'false']))};

insert into public.team_permissions (permission) values
${values(TEAM_PERMISSION_FLAGS.map(permission => [sqlLiteral(permission)]))};

insert into public.role_permissions (role, permission, allowed) values
${values(roleRows)};

insert into public.team_error_codes (code) values
${values(TEAM_ERROR_CODES.map(code => [sqlLiteral(code)]))};

insert into public.geo_options (code) values
${values(GEO_CODES.map(code => [sqlLiteral(code)]))};

insert into public.language_options (code) values
${values(LANGUAGE_CODES.map(code => [sqlLiteral(code)]))};

alter table public.team_contract_settings enable row level security;
alter table public.team_contract_settings force row level security;
alter table public.team_roles enable row level security;
alter table public.team_roles force row level security;
alter table public.team_permissions enable row level security;
alter table public.team_permissions force row level security;
alter table public.role_permissions enable row level security;
alter table public.role_permissions force row level security;
alter table public.team_error_codes enable row level security;
alter table public.team_error_codes force row level security;
alter table public.geo_options enable row level security;
alter table public.geo_options force row level security;
alter table public.language_options enable row level security;
alter table public.language_options force row level security;

revoke all on table public.team_contract_settings from public, anon, authenticated;
revoke all on table public.team_roles from public, anon, authenticated;
revoke all on table public.team_permissions from public, anon, authenticated;
revoke all on table public.role_permissions from public, anon, authenticated;
revoke all on table public.team_error_codes from public, anon, authenticated;
revoke all on table public.geo_options from public, anon, authenticated;
revoke all on table public.language_options from public, anon, authenticated;

comment on table public.team_contract_settings is
  'Generated Soty team contract settings; regenerate from shared TypeScript.';
`;
}

const args = process.argv.slice(2);
let check = false;
let output = defaultOutput;
for (let index = 0; index < args.length; index += 1) {
  if (args[index] === '--check') check = true;
  else if (args[index] === '--output' && args[index + 1]) output = resolve(args[++index]);
  else fail(`Unknown argument: ${args[index]}`);
}

const next = generatedSql();
if (check) {
  let current = '';
  try {
    current = readFileSync(output, 'utf8');
  } catch {
    fail(`Generated team contract is out of date: ${output}`);
  }
  // Git checks text files out with CRLF on the Windows runner. The generated
  // contract is canonical LF, so compare content rather than checkout-specific
  // line endings; otherwise an unchanged migration is reported as stale only
  // on Windows.
  if (current.replaceAll('\r\n', '\n') !== next) {
    fail(`Generated team contract is out of date: ${output}`);
  }
  process.stdout.write(`Team contract is current: ${output}\n`);
} else {
  writeFileSync(output, next);
  process.stdout.write(`Generated team contract: ${output}\n`);
}
