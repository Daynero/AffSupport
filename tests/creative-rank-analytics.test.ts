import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { createAnalyticsDb, type AnalyticsTestDb } from './support/analytics-pglite';
import { getCreativeRankDiagnosis } from '../scripts/analytics/creative-ranks';
import { COVERAGE_REGISTRY } from '../scripts/analytics/coverage-registry';

/**
 * Feature 059: an agent explains a creative's count from the ledger alone — which Launch or
 * catalog credited it, which pair counted once, and a demotion — without opening the database
 * by hand or asking the owner.
 */

const TEAM = 'c5910000-0000-4000-8000-000000000011';
const VIDEO = 'c5910000-0000-4000-8000-000000000041';
const LAUNCH = 'c5910000-0000-4000-8000-000000000101';
const PAIRED_LAUNCH = 'c5910000-0000-4000-8000-000000000102';
const CATALOG = 'c5910000-0000-4000-8000-000000000051';
const PAIRED_CATALOG = 'c5910000-0000-4000-8000-000000000052';

let db: AnalyticsTestDb;
beforeAll(async () => {
  db = await createAnalyticsDb();
  await db.exec(`
    create table public.team_creative_launch_events(
      id bigint generated by default as identity primary key, team_id uuid, material_id uuid,
      source_kind text, source_id uuid, occurred_at timestamptz, counted boolean,
      absorbed_by_launch_id uuid, backfilled boolean, created_at timestamptz default now());
    create table public.team_creative_ranks(
      team_id uuid, material_id uuid, launch_count integer, rank_credit integer,
      last_launched_at timestamptz, demoted_at timestamptz, demoted_by uuid, demote_reason text,
      demote_request_key text, version bigint, updated_at timestamptz);
    insert into public.team_creative_launch_events(team_id,material_id,source_kind,source_id,occurred_at,counted,absorbed_by_launch_id,backfilled) values
      ('${TEAM}','${VIDEO}','launch','${LAUNCH}','2026-11-10T10:00Z',true,null,true),
      ('${TEAM}','${VIDEO}','catalog','${CATALOG}','2026-11-11T10:00Z',true,null,false),
      ('${TEAM}','${VIDEO}','catalog','${PAIRED_CATALOG}','2026-11-12T10:00Z',true,'${PAIRED_LAUNCH}',false),
      ('${TEAM}','${VIDEO}','launch','${PAIRED_LAUNCH}','2026-11-12T10:05Z',false,null,false);
    insert into public.team_creative_ranks values
      ('${TEAM}','${VIDEO}',3,1,'2026-11-12T10:05Z','2026-11-13T09:00Z',null,'disappointed','owner-attempt-1',7,now());
  `);
}, 30000);
afterAll(async () => db?.close());

describe('creative-rank', () => {
  it('explains a video: credited rows, the paired Launch and catalog, and the demotion', async () => {
    const result = await getCreativeRankDiagnosis(VIDEO);
    expect(result.supported).toBe(true);
    expect(result.matched).toBe('material');
    expect(result.ranks).toEqual([
      expect.objectContaining({
        launch_count: 3,
        rank_credit: 1,
        demoted: expect.objectContaining({ reason: 'disappointed' })
      })
    ]);
    expect(result.events.filter(e => e.effect === 'credited')).toHaveLength(3);
    expect(result.events.find(e => e.source_id === PAIRED_LAUNCH)?.effect).toBe('paired');
    expect(result.explanation.join(' ')).toMatch(/count once/);
    expect(result.explanation.join(' ')).toMatch(/demoted it \(disappointed\)/);
  });

  it('resolves a Launch id to the creative it credited', async () => {
    const result = await getCreativeRankDiagnosis(LAUNCH);
    expect(result.matched).toBe('launch');
    expect(result.ranks[0]?.material_id).toBe(VIDEO);
  });

  it('lists a team', async () => {
    const result = await getCreativeRankDiagnosis(TEAM);
    expect(result.matched).toBe('team');
    expect(result.ranks).toHaveLength(1);
  });

  it('says why an unknown id has nothing, and never pretends Facebook is seen', async () => {
    const result = await getCreativeRankDiagnosis('c5910000-0000-4000-8000-000000000999');
    expect(result.matched).toBe('none');
    expect(result.explanation[0]).toMatch(/first successful generation/);
    expect(result.blind_spots.join(' ')).toMatch(/Facebook/);
  });
});

describe('coverage', () => {
  it('registers the demotion journey and the database credit', () => {
    const ids = COVERAGE_REGISTRY.map(capability => capability.id);
    expect(ids).toContain('team.creative_rank_demote');
    expect(ids).toContain('team.creative_rank_credit');
  });
});
