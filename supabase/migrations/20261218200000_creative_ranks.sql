-- Backfill from history, kept as a function so a repair can run it again. Idempotent: every event
-- is keyed by its source, and the projection is recomputed from the ledger, keeping how far the
-- owner demoted each creative. Ledger rows are written without per-row projection updates or
-- realtime announcements; one set-based pass builds the projection at the end.
-- Order: catalogs, then Launches (each absorbs the catalog of its first success), then every other
-- catalog a credited Launch went through (regenerations) — exactly what the live triggers do.
create function private.backfill_creative_ranks() returns integer
language plpgsql security definer set search_path = '' as $$
declare
  c record;
  l record;
  v_changed integer;
begin
  for c in
    select p.team_id, p.video_material_id, p.material_id, p.created_at
      from public.team_product_catalogs p
     where p.video_material_id is not null
     order by p.created_at, p.material_id
  loop
    perform private.apply_creative_rank_event(
      c.team_id, c.video_material_id, 'catalog', c.material_id, c.created_at, null, true
    );
  end loop;

  for l in
    select distinct on (g.launch_id)
           g.team_id, g.launch_id, g.updated_at, r.config ->> 'materialId' as material_text,
           rc.catalog_id
      from public.team_launch_generations g
      join public.team_launch_revisions r on r.id = g.revision_id and r.team_id = g.team_id
      left join public.team_launch_revision_catalogs rc on rc.revision_id = g.revision_id and rc.team_id = g.team_id
     where g.state = 'succeeded'
     order by g.launch_id, g.updated_at, g.id
  loop
    if l.material_text ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$' then
      perform private.apply_creative_rank_event(
        l.team_id, l.material_text::uuid, 'launch', l.launch_id, l.updated_at, l.catalog_id, true
      );
    end if;
  end loop;

  for c in
    select rc.team_id, r.launch_id, rc.catalog_id
      from public.team_launch_revision_catalogs rc
      join public.team_launch_revisions r on r.id = rc.revision_id and r.team_id = rc.team_id
     order by r.created_at, rc.revision_id
  loop
    perform private.absorb_launch_catalog(c.team_id, c.launch_id, c.catalog_id, true);
  end loop;

  with ledger as (
    select e.team_id, e.material_id,
           (count(*) filter (where e.counted))::integer as launches,
           max(e.occurred_at) as last_at
      from public.team_creative_launch_events e
     group by e.team_id, e.material_id
  )
  insert into public.team_creative_ranks as r (team_id, material_id, launch_count, rank_credit, last_launched_at)
  select team_id, material_id, launches, launches, last_at from ledger
  on conflict (team_id, material_id) do update
    set launch_count = excluded.launch_count,
        rank_credit = greatest(r.rank_credit + excluded.launch_count - r.launch_count, 0),
        last_launched_at = excluded.last_launched_at,
        version = r.version + 1,
        updated_at = pg_catalog.clock_timestamp()
    where r.launch_count is distinct from excluded.launch_count
       or r.last_launched_at is distinct from excluded.last_launched_at;
  get diagnostics v_changed = row_count;
  return v_changed;
end;
$$;
revoke all on function private.backfill_creative_ranks() from public, anon, authenticated;

select private.backfill_creative_ranks();

-- Realtime: a rank change is announced as its own catalog event kind, so the web re-reads ranks
-- only, not the folder page. Older web builds treat an unknown kind as a full catalog read.
-- Last, so the exclusive lock on this busy table is held only to the commit; NOT VALID because the
-- set only grows — every existing row already passes, and a full scan under that lock buys nothing.
alter table public.team_catalog_events drop constraint team_catalog_events_kind_check;
alter table public.team_catalog_events add constraint team_catalog_events_kind_check check (event_kind in (
  'upserted', 'tombstoned', 'restored', 'sync_state', 'folder_indexed', 'thumbnail_ready',
  'storage_state', 'bulk_trash_changed', 'creative_rank'
)) not valid;
