-- Realtime: a rank change is announced as its own catalog event kind, so the web re-reads ranks
-- only, not the folder page. Older web builds treat an unknown kind as a full catalog read.
alter table public.team_catalog_events drop constraint team_catalog_events_kind_check;
alter table public.team_catalog_events add constraint team_catalog_events_kind_check check (event_kind in (
  'upserted', 'tombstoned', 'restored', 'sync_state', 'folder_indexed', 'thumbnail_ready',
  'storage_state', 'bulk_trash_changed', 'creative_rank'
));

-- Adds `delta` to a creative's projection and moves its last launch forward. One event, one call.
create function private.bump_creative_rank(
  p_team uuid, p_material uuid, p_delta integer, p_occurred_at timestamptz
) returns void
language plpgsql security definer set search_path = '' as $$
begin
  insert into public.team_creative_ranks as r (team_id, material_id, launch_count, rank_credit, last_launched_at)
  values (p_team, p_material, p_delta, p_delta, p_occurred_at)
  on conflict (team_id, material_id) do update
    set launch_count = r.launch_count + p_delta,
        rank_credit = r.rank_credit + p_delta,
        last_launched_at = greatest(r.last_launched_at, excluded.last_launched_at),
        version = r.version + 1,
        updated_at = pg_catalog.clock_timestamp();
  insert into public.team_catalog_events (team_id, material_id, event_kind)
  values (p_team, p_material, 'creative_rank');
end;
$$;

-- The one writer of the ledger. Returns whether the event was new.
create function private.apply_creative_rank_event(
  p_team uuid, p_material uuid, p_kind text, p_source uuid, p_occurred_at timestamptz,
  p_catalog uuid default null, p_backfilled boolean default false
) returns boolean
language plpgsql security definer set search_path = '' as $$
declare
  v_counted boolean := true;
  v_absorbed uuid;
  v_catalog_event public.team_creative_launch_events%rowtype;
begin
  if p_team is null or p_material is null or p_source is null or p_occurred_at is null then
    return false;
  end if;
  if not exists (select 1 from public.team_materials m where m.id = p_material and m.team_id = p_team) then
    return false;
  end if;
  if exists (
    select 1 from public.team_creative_launch_events e
     where e.team_id = p_team and e.source_kind = p_kind and e.source_id = p_source
  ) then
    return false;
  end if;

  if p_kind = 'launch' and p_catalog is not null then
    -- The Launch made (or reuses) catalog C. If C was credited on its own and nobody absorbed it
    -- yet, the Launch takes C's credit over instead of adding a second one.
    select * into v_catalog_event
      from public.team_creative_launch_events e
     where e.team_id = p_team and e.source_kind = 'catalog' and e.source_id = p_catalog
     for update;
    if v_catalog_event.id is not null and v_catalog_event.absorbed_by_launch_id is null
       and v_catalog_event.material_id = p_material then
      update public.team_creative_launch_events
         set absorbed_by_launch_id = p_source
       where id = v_catalog_event.id;
      v_counted := not v_catalog_event.counted;
    end if;
  elsif p_kind = 'catalog' then
    -- The catalog belongs to a Launch whose success is already credited: absorb it at once.
    select e.source_id into v_absorbed
      from public.team_launch_revision_catalogs c
      join public.team_launch_revisions r on r.id = c.revision_id and r.team_id = c.team_id
      join public.team_creative_launch_events e
        on e.team_id = c.team_id and e.source_kind = 'launch' and e.source_id = r.launch_id
     where c.team_id = p_team and c.catalog_id = p_source and e.material_id = p_material
       and not exists (
         select 1 from public.team_creative_launch_events other
          where other.team_id = p_team and other.source_kind = 'catalog'
            and other.absorbed_by_launch_id = e.source_id
       )
     order by e.occurred_at
     limit 1;
    if v_absorbed is not null then
      v_counted := false;
    end if;
  end if;

  insert into public.team_creative_launch_events
    (team_id, material_id, source_kind, source_id, occurred_at, counted, absorbed_by_launch_id, backfilled)
  values
    (p_team, p_material, p_kind, p_source, p_occurred_at, v_counted, v_absorbed, p_backfilled)
  on conflict (team_id, source_kind, source_id) do nothing;
  if not found then
    return false;
  end if;

  perform private.bump_creative_rank(p_team, p_material, case when v_counted then 1 else 0 end, p_occurred_at);
  return true;
end;
$$;

create function private.credit_launch_rank() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  v_material uuid;
  v_catalog uuid;
  v_material_text text;
begin
  if new.state <> 'succeeded' or old.state = 'succeeded' then
    return null;
  end if;
  begin
    select r.config ->> 'materialId' into v_material_text
      from public.team_launch_revisions r
     where r.id = new.revision_id and r.team_id = new.team_id;
    if v_material_text is null
       or v_material_text !~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$' then
      return null;
    end if;
    v_material := v_material_text::uuid;
    select c.catalog_id into v_catalog
      from public.team_launch_revision_catalogs c
     where c.revision_id = new.revision_id and c.team_id = new.team_id;
    perform private.apply_creative_rank_event(
      new.team_id, v_material, 'launch', new.launch_id, new.updated_at, v_catalog
    );
  exception when unique_violation or foreign_key_violation or check_violation then
    -- A ledger race or a vanished row must not undo a published Launch.
    null;
  end;
  return null;
end;
$$;

create function private.credit_catalog_rank() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if new.video_material_id is null then
    return null;
  end if;
  begin
    perform private.apply_creative_rank_event(
      new.team_id, new.video_material_id, 'catalog', new.material_id, new.created_at
    );
  exception when unique_violation or foreign_key_violation or check_violation then
    null;
  end;
  return null;
end;
$$;

-- Deferred: a publication writes its revision catalog and its state in separate steps of one
-- transaction; at commit everything the commit makes true is visible.
create constraint trigger team_launch_generations_credit_rank
  after update of state on public.team_launch_generations
  deferrable initially deferred
  for each row execute function private.credit_launch_rank();
create constraint trigger team_product_catalogs_credit_rank
  after insert on public.team_product_catalogs
  deferrable initially deferred
  for each row execute function private.credit_catalog_rank();

create function private.creative_rank_json(r public.team_creative_ranks) returns jsonb
language sql stable set search_path = '' as $$
  select jsonb_build_object(
    'materialId', r.material_id,
    'launchCount', r.launch_count,
    'rankCredit', r.rank_credit,
    'lastLaunchedAt', r.last_launched_at,
    'version', r.version,
    'demotion', case when r.demoted_at is null then null
                     else jsonb_build_object('reason', r.demote_reason, 'at', r.demoted_at) end
  );
$$;

create function public.list_creative_ranks(p_team uuid, p_materials uuid[]) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
begin
  if not private.can(p_team, 'view') then
    raise exception 'PERMISSION_DENIED' using errcode = '42501';
  end if;
  if p_materials is null or cardinality(p_materials) < 1 or cardinality(p_materials) > 500 then
    raise exception 'INVALID_INPUT' using errcode = '22023';
  end if;
  return coalesce((
    select jsonb_agg(private.creative_rank_json(r) order by r.material_id)
      from public.team_creative_ranks r
     where r.team_id = p_team and r.material_id = any (p_materials)
  ), '[]'::jsonb);
end;
$$;

create function public.demote_creative_rank(
  p_team uuid, p_material uuid, p_reason text, p_target_credit integer,
  p_expected_version bigint, p_request_key text
) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  r public.team_creative_ranks%rowtype;
begin
  if private.team_role(p_team, auth.uid()) is distinct from 'owner' then
    raise exception 'PERMISSION_DENIED' using errcode = '42501';
  end if;
  if p_material is null or p_reason is null or p_reason not in ('disappointed', 'never_launched')
     or p_target_credit is null or p_expected_version is null
     or p_request_key is null or char_length(p_request_key) not between 8 and 200 then
    raise exception 'INVALID_INPUT' using errcode = '22023';
  end if;

  select * into r from public.team_creative_ranks
   where team_id = p_team and material_id = p_material
   for update;
  if r.material_id is null then
    raise exception 'RANK_NOT_LOWER' using errcode = 'PT409';
  end if;
  if r.demote_request_key = p_request_key then
    return private.creative_rank_json(r);
  end if;
  if r.version <> p_expected_version then
    raise exception 'RANK_CONFLICT' using errcode = 'PT409', detail = private.creative_rank_json(r)::text;
  end if;
  if p_target_credit < 0 or p_target_credit >= r.rank_credit then
    raise exception 'RANK_NOT_LOWER' using errcode = 'PT409', detail = private.creative_rank_json(r)::text;
  end if;

  update public.team_creative_ranks
     set rank_credit = p_target_credit,
         demoted_at = pg_catalog.clock_timestamp(),
         demoted_by = auth.uid(),
         demote_reason = p_reason,
         demote_request_key = p_request_key,
         version = version + 1,
         updated_at = pg_catalog.clock_timestamp()
   where team_id = p_team and material_id = p_material
   returning * into r;
  insert into public.team_catalog_events (team_id, material_id, event_kind)
  values (p_team, p_material, 'creative_rank');
  return private.creative_rank_json(r);
end;
$$;

