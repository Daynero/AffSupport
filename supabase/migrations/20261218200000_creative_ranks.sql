-- Backfill from history. Idempotent: every event is keyed by its source.
-- Catalogs first, then Launches, so each Launch absorbs its own catalog exactly as it would live.
do $$
declare
  c record;
  l record;
begin
  for c in
    select p.team_id, p.video_material_id, p.material_id, p.created_at
      from public.team_product_catalogs p
     where p.video_material_id is not null
     order by p.created_at, p.material_id
  loop
    perform private.apply_creative_rank_event(
      c.team_id, c.video_material_id, 'catalog', c.material_id, c.created_at, null, true
    );
  end loop;

  for l in
    select distinct on (g.launch_id)
           g.team_id, g.launch_id, g.updated_at, r.config ->> 'materialId' as material_text,
           rc.catalog_id
      from public.team_launch_generations g
      join public.team_launch_revisions r on r.id = g.revision_id and r.team_id = g.team_id
      left join public.team_launch_revision_catalogs rc on rc.revision_id = g.revision_id and rc.team_id = g.team_id
     where g.state = 'succeeded'
     order by g.launch_id, g.updated_at, g.id
  loop
    if l.material_text ~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$' then
      perform private.apply_creative_rank_event(
        l.team_id, l.material_text::uuid, 'launch', l.launch_id, l.updated_at, l.catalog_id, true
      );
    end if;
  end loop;
end $$;

-- The backfill announced every creative it touched; nobody needs those as live invalidations.
delete from public.team_catalog_events where event_kind = 'creative_rank';
