-- 059: creative ranks (honey leagues).
--
-- A creative's rank records how proven it is: how many times it was launched and when last.
-- The count only grows; the league credit grows with it and falls only when the space owner
-- demotes it by hand. Leagues and freshness are derived in the web app from these two numbers,
-- so thresholds live in one place there and never need a migration.
--
-- A launch is credited inside the transaction that makes it true, by triggers, never by a client:
--   * the first generation of a Launch to reach `succeeded` credits the Launch's video;
--   * a product catalog inserted for a video credits that video;
--   * a catalog that a Launch made is credited once, through the Launch (absorption).
--   * every later catalog of an already credited Launch (a regeneration) is absorbed too: one
--     Launch is one launch, however many sheets it went through.
-- Crediting must never break the operation it observes: anything it cannot attribute is skipped.

-- Fail fast instead of queueing behind a long transaction: a waiting ALTER blocks every writer
-- behind it. A refused deploy is retried; a stalled sync is not noticed.
set local lock_timeout = '5s';

create table public.team_creative_launch_events (
  id bigint generated by default as identity primary key,
  team_id uuid not null references public.teams(id) on delete cascade,
  material_id uuid not null,
  source_kind text not null,
  source_id uuid not null,
  occurred_at timestamptz not null,
  counted boolean not null,
  absorbed_by_launch_id uuid,
  backfilled boolean not null default false,
  created_at timestamptz not null default now(),
  constraint team_creative_launch_events_kind_check check (source_kind in ('launch', 'catalog')),
  constraint team_creative_launch_events_absorbed_check
    check (absorbed_by_launch_id is null or source_kind = 'catalog'),
  constraint team_creative_launch_events_source_unique unique (team_id, source_kind, source_id)
);
create index team_creative_launch_events_material_idx
  on public.team_creative_launch_events (team_id, material_id, occurred_at desc);

create table public.team_creative_ranks (
  team_id uuid not null references public.teams(id) on delete cascade,
  material_id uuid not null,
  launch_count integer not null default 0 check (launch_count >= 0),
  rank_credit integer not null default 0 check (rank_credit >= 0),
  last_launched_at timestamptz,
  demoted_at timestamptz,
  demoted_by uuid references auth.users(id) on delete set null,
  demote_reason text check (demote_reason in ('disappointed', 'never_launched')),
  demote_request_key text check (demote_request_key is null or char_length(demote_request_key) between 8 and 200),
  -- The owner's way back up after a mistaken demotion: never past what the launches earned.
  promoted_at timestamptz,
  promoted_by uuid references auth.users(id) on delete set null,
  promote_request_key text check (promote_request_key is null or char_length(promote_request_key) between 8 and 200),
  version bigint not null default 1,
  updated_at timestamptz not null default now(),
  primary key (team_id, material_id)
);

