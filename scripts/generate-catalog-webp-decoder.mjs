/** Reproduce the offline Edge decoder from the exact, already-installed published artifact. */
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const upstream = path.join(root, 'node_modules/playwright-core');
const output = path.join(root, 'supabase/functions/_shared/catalog-webp');
const version = '1.62.1';
const integrity =
  'sha512-wPYSwEBJY9GHraISXqyqtx0na0LpO3XEX7jNDhntbex7tzUS7kLnZsOlFruFJB4Hi/rhDMjXGqHewDZ68nYZVw==';
const hashes = {
  'lib/coreBundle.js': '9393fa79e1c67c74edc26b610d65a4f7ed73d345a762465cc88340a33a2454ac',
  'lib/webp_codec.wasm': '164cd9583a3e4d081f767d3b41ff0a730443dc7535fcc5caff83561463384b79',
  'lib/webp_codec.LICENSE': '995c7ee35aceb7666829b7a501ca89c0864e12b493c1174b155774ab1e03d831'
};
const args = process.argv.slice(2);
if (args.some(arg => arg !== '--check') || args.length > 1)
  throw new Error('Usage: node scripts/generate-catalog-webp-decoder.mjs [--check]');
const check = args.includes('--check');
const installed = JSON.parse(readFileSync(path.join(upstream, 'package.json'), 'utf8'));
const lock = JSON.parse(readFileSync(path.join(root, 'package-lock.json'), 'utf8'));
const locked = lock.packages?.['node_modules/playwright-core'];
if (installed.version !== version || locked?.version !== version || locked.integrity !== integrity)
  throw new Error(
    'The catalog WebP decoder requires the reviewed playwright-core 1.62.1 artifact.'
  );

function input(name) {
  const bytes = readFileSync(path.join(upstream, name));
  if (createHash('sha256').update(bytes).digest('hex') !== hashes[name])
    throw new Error(`Unexpected upstream codec bytes: ${name}`);
  return bytes;
}

function replaceExactlyOnce(source, before, after) {
  if (source.split(before).length !== 2)
    throw new Error('The reviewed WebP decoder patch no longer matches exactly once.');
  return source.replace(before, after);
}

const bundle = input('lib/coreBundle.js').toString('utf8');
const marker = '// packages/utils/webp/webp_codec.js\n';
if (bundle.split(marker).length !== 2) throw new Error('Published codec section is not unique.');
const section = bundle.split(marker)[1].split('\n// packages/utils/webp/webp.ts')[0];
const start = section.indexOf('var Module = (() => {');
const end = section.lastIndexOf('    })();');
if (start < 0 || end <= start) throw new Error('The published Emscripten factory is missing.');
let decoder = section.slice(start, end + '    })();'.length);
decoder = replaceExactlyOnce(
  decoder,
  '      var _scriptName = globalThis.document?.currentScript?.src;\n',
  ''
);
// Replace the complete Node/DOM/network loader with the only supported embedded-byte path.
const loaderStart = decoder.indexOf('        var ENVIRONMENT_IS_WEB =');
const loaderEnd = decoder.indexOf('        var out = console.log.bind(console);', loaderStart);
if (loaderStart < 0 || loaderEnd <= loaderStart) throw new Error('Known codec loader is missing.');
decoder = replaceExactlyOnce(
  decoder,
  decoder.slice(loaderStart, loaderEnd),
  `        var programArgs = [];
        var thisProgram = './this.program';
        var quit_ = (_status, toThrow) => { throw toThrow; };
        var locateFile = () => 'embedded:webp_codec.wasm';
        var readBinary;
`
);
decoder = replaceExactlyOnce(
  decoder,
  'var getHeapMax = () => 2147483648;',
  'var getHeapMax = () => 134217728;'
);
if (
  /\b(?:require|fetch)\s*\(|\bImageData\b|globalThis\.|\b(?:__dirname|__filename)\b/u.test(decoder)
)
  throw new Error('The generated codec still contains a host loader or global dependency.');
const banner = `/* eslint-disable -- Generated third-party Emscripten glue; see README.md. */
/*
 * Published playwright-core ${version}; Apache-2.0. Codec and runtime: see LICENSE.codec.txt.
 * Generated by scripts/generate-catalog-webp-decoder.mjs; DO NOT EDIT.
 * Modified: extracted ESM factory; removed host loaders; limited heap growth to 128 MiB.
 * libwebp source: 3757b8afeb54e305eaef18502812a9a88b7ed662 (official post-1.6.0 commit).
 * Published coreBundle.js SHA-256: ${hashes['lib/coreBundle.js']}
 */
// prettier-ignore
`;
const wasm = input('lib/webp_codec.wasm');
const wasmSource = `// Generated by scripts/generate-catalog-webp-decoder.mjs; DO NOT EDIT.
// Published playwright-core ${version}; see README.md and LICENSE.*.txt.
// Exact WASM SHA-256: ${hashes['lib/webp_codec.wasm']}
export const CATALOG_WEBP_WASM_SHA256 =
  '${hashes['lib/webp_codec.wasm']}';
export const CATALOG_WEBP_WASM_BASE64 =
  '${wasm.toString('base64')}';
`;
const files = new Map([
  ['decoder.js', banner + decoder.trim() + '\nexport default Module;\n'],
  ['wasm.ts', wasmSource],
  ['LICENSE.apache-2.0.txt', readFileSync(path.join(upstream, 'LICENSE'), 'utf8')],
  ['LICENSE.codec.txt', input('lib/webp_codec.LICENSE').toString('utf8')]
]);
if (!check) mkdirSync(output, { recursive: true });
for (const [name, contents] of files) {
  const destination = path.join(output, name);
  if (check) {
    if (readFileSync(destination, 'utf8') !== contents)
      throw new Error(`Generated decoder differs: ${name}`);
  } else writeFileSync(destination, contents);
}
process.stdout.write(
  `Catalog WebP decoder ${check ? 'verified' : 'generated'} (${wasm.length} WASM bytes).\n`
);
